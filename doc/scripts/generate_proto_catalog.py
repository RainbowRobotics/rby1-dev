#!/usr/bin/env python3
"""Write the service and module lists of manual/sdk/protos/index.md from protoc-gen-doc output.

Only the part between the BEGIN/END markers is replaced; the overview above it is written by hand.
The site sidebar follows the links of that page in order (manual/.vitepress/config.mts, linkTree),
so services come first and service-only modules link straight to their service page.

Input: doc/source/sdk/protos/generated/protos.json (make protoc-doc writes it).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTOS_JSON = ROOT / "source" / "sdk" / "protos" / "generated" / "protos.json"
INDEX_MD = ROOT.parent / "manual" / "sdk" / "protos" / "index.md"
BEGIN = "<!-- BEGIN generated by doc/scripts/generate_proto_catalog.py -->"
END = "<!-- END generated by doc/scripts/generate_proto_catalog.py -->"


def slugify(name: str) -> str:
    # Same page names as generate_proto_type_pages.py.
    slug = re.sub(r"[^a-z0-9_-]+", "-", name.strip().lower().replace(".", "-"))
    return re.sub(r"-{2,}", "-", slug).strip("-") or "type"


def module_of(proto_file: str) -> str:
    return proto_file.rsplit("/", 1)[-1].removesuffix(".proto")


def streaming(method: dict) -> str:
    client, server = method["requestStreaming"], method["responseStreaming"]
    if client and server:
        return f"{method['name']} (bidirectional stream)"
    if client:
        return f"{method['name']} (client stream)"
    if server:
        return f"{method['name']} (server stream)"
    return method["name"]


def catalog(data: dict) -> str:
    files = sorted(data["files"], key=lambda f: f["name"])
    lines = [BEGIN, "", "## Services", "", "| Service | RPCs |", "| --- | --- |"]
    for f in files:
        for s in f["services"]:
            page = f"./generated/{module_of(f['name'])}/{slugify(s['longName'])}.md"
            rpcs = ", ".join(streaming(m) for m in s["methods"])
            lines.append(f"| [{s['longName']}]({page}) | {rpcs} |")
    lines += ["", "## Messages by proto file", ""]
    for f in files:
        if not (f["messages"] or f["enums"]):
            continue  # service-only file: its service is listed above
        module = module_of(f["name"])
        lines.append(f"- [{module}.proto](./generated/{module}/index.md)")
    lines += ["- [Scalar Value Types](./generated/scalar-value-types.md)", "", END]
    return "\n".join(lines)


def main() -> None:
    data = json.loads(PROTOS_JSON.read_text(encoding="utf-8"))
    text = INDEX_MD.read_text(encoding="utf-8")
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise RuntimeError(f"{INDEX_MD}: markers {BEGIN!r} ... {END!r} not found")
    INDEX_MD.write_text(text[:start] + catalog(data) + text[end + len(END):], encoding="utf-8")
    print(f"[proto-catalog] updated {INDEX_MD}")


if __name__ == "__main__":
    main()
