#!/usr/bin/env python3
"""One-time migration of the Sphinx manual (doc/source) to the VitePress site (manual/), kept for reference.

- Markdown (MyST) pages are converted with myst_to_vitepress.convert.
- Proto module index pages (reStructuredText toctrees) become Markdown link lists.
- Images and videos are copied to manual/public/.
Not migrated here: the Python and C++ API sources (generated by scripts/generate_reference.py),
the joint limit tables (generated), and the hand-written .rst landing pages (rewritten by hand).

Usage: python3 manual/scripts/migrate_from_sphinx.py [--src doc/source] [--dst manual]
"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

from myst_to_vitepress import convert
from rst_index import rst_toctree_index, title_of  # noqa: F401  (kept importable from here)

SKIP_PREFIXES = ("sdk/python/", "sdk/cpp/", "hardware/generated/", "_static/", "_templates/")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--src", type=Path, default=Path("doc/source"))
    parser.add_argument("--dst", type=Path, default=Path("manual"))
    args = parser.parse_args()

    converted = 0
    for md in sorted(args.src.rglob("*.md")):
        rel = md.relative_to(args.src).as_posix()
        if rel.startswith(SKIP_PREFIXES):
            continue
        out = args.dst / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(convert(md.read_text()))
        converted += 1

    proto_indexes = 0
    for rst in sorted((args.src / "sdk/protos/generated").rglob("*.rst")):
        out = args.dst / rst.relative_to(args.src).with_suffix(".md")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(rst_toctree_index(rst, args.src))
        proto_indexes += 1

    for media in ("images", "videos"):
        src = args.src / "_static" / media
        if src.is_dir():
            shutil.copytree(src, args.dst / "public" / media, dirs_exist_ok=True)

    print(f"[migrate] {converted} Markdown pages, {proto_indexes} proto index pages, media copied")


if __name__ == "__main__":
    main()
