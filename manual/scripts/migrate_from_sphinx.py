#!/usr/bin/env python3
"""One-time migration of the Sphinx manual (doc/source) to the VitePress site (manual/).

- Markdown (MyST) pages are converted with myst_to_vitepress.convert.
- Proto module index pages (reStructuredText toctrees) become Markdown link lists.
- Images and videos are copied to manual/public/.
Not migrated here: the Python and C++ API sources (generated by scripts/export_api_markdown.py),
the joint limit tables (generated), and the hand-written .rst landing pages (rewritten by hand).

Usage: python3 manual/scripts/migrate_from_sphinx.py [--src doc/source] [--dst manual]
"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

from myst_to_vitepress import convert

SKIP_PREFIXES = ("sdk/python/", "sdk/cpp/", "hardware/generated/", "_static/", "_templates/")


def title_of(md: Path) -> str:
    for line in md.read_text().splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return md.stem


def rst_title(rst: Path) -> str:
    lines = rst.read_text().splitlines()
    for i in range(len(lines) - 1):
        if lines[i].strip() and re.fullmatch(r"[=\-~^]{3,}", lines[i + 1].strip()):
            return lines[i].strip()
    return rst.stem


def rst_toctree_index(rst: Path, src_root: Path) -> str:
    """Title, intro paragraphs and toctree of a simple .rst index page -> Markdown with a link list."""
    lines = rst.read_text().splitlines()
    title = rst_title(rst)
    intro, entries, in_toc, seen_title = [], [], False, False
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith(".. toctree::"):
            in_toc = True
            continue
        if in_toc:
            if not s or s.startswith(":"):
                continue
            if line.startswith(" "):
                entries.append(s)
                continue
            in_toc = False
        if s == title:
            seen_title = True
            continue
        if not seen_title or re.fullmatch(r"[=\-~^]{3,}", s) or s.startswith(".. "):
            continue
        intro.append(line)
    out = [f"# {title}", ""] + [l for l in "\n".join(intro).strip().splitlines()] + ([""] if intro else [])
    for e in entries:
        target = rst.parent / e
        md, rs = target.with_suffix(".md"), target.with_suffix(".rst")
        label = title_of(md) if md.exists() else rst_title(rs) if rs.exists() else e
        out.append(f"- [{label}](./{e}.md)")
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--src", type=Path, default=Path("doc/source"))
    parser.add_argument("--dst", type=Path, default=Path("manual"))
    args = parser.parse_args()

    converted = 0
    for md in sorted(args.src.rglob("*.md")):
        rel = md.relative_to(args.src).as_posix()
        if rel.startswith(SKIP_PREFIXES):
            continue
        out = args.dst / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(convert(md.read_text()))
        converted += 1

    proto_indexes = 0
    for rst in sorted((args.src / "sdk/protos/generated").rglob("*.rst")):
        out = args.dst / rst.relative_to(args.src).with_suffix(".md")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(rst_toctree_index(rst, args.src))
        proto_indexes += 1

    for media in ("images", "videos"):
        src = args.src / "_static" / media
        if src.is_dir():
            shutil.copytree(src, args.dst / "public" / media, dirs_exist_ok=True)

    print(f"[migrate] {converted} Markdown pages, {proto_indexes} proto index pages, media copied")


if __name__ == "__main__":
    main()
